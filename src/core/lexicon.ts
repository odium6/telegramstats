// Словари напряжения и примирения (для поиска напряжённых периодов).
// Границы слов — через (?<!\p{L}) / (?!\p{L}): в JS \b не работает с кириллицей.
// Проверено на реальной переписке: слова, которые чаще встречаются вне ссор
// («хватит» денег, «ты всегда красивая», «мама будет ругаться», разговоры о
// чужих ссорах), заменены на более узкие формы.
const W0 = '(?<![\\p{L}])';
const W1 = '(?![\\p{L}])';
const rx = (src: string) => new RegExp(src, 'iu');

export const CONFLICT_RE = rx(
  `${W0}(` +
    [
      'я обиделась|я обиделся|ты обиделась|ты обиделся|обиделась\\??$|обиделся\\??$|обидно мне|мне обидно|обидно$|обижаешься|обижаешь меня|обижаюсь',
      'бесишь|бесит меня|ты меня бесишь|надоело|надоел мне|надоела мне|ты меня достал\\p{L}*|достал уже|достала уже',
      'отстань|отвали|не пиши мне|не хочу (с тобой )?(разговаривать|общаться)|ну и пожалуйста|ну и ладно|как хочешь\\.?$|мне все равно|мне всё равно',
      'хватит(\\s+(уже|меня|орать|кричать|ныть|пожалуйста|это))|хватит[.!]*$',
      'ты (всегда|никогда|опять|снова) (не |так |меня |забываешь|опаздываешь|игнор|молчишь|делаешь|говоришь|начинаешь)',
      'почему ты (опять|снова|не отвечаешь|молчишь|игнор\\p{L}*|так со мной)',
      'ты издеваешься|ты серь[её]зно\\?|ты нормальн(ый|ая)\\?|я устал\\p{L}* от (тебя|этого)',
      'не ори|не кричи|кричишь на меня|игнор\\p{L}*|не слышишь меня|ты не понимаешь|ты меня не понимаешь|мне больно',
      'расстаться|расстанемся|давай расстанемся|разойтись|ненавижу тебя|я тебя ненавижу|я злюсь|ты злишься|злишься на меня|я зла на тебя|я зол на тебя',
      'молчишь|бросишь меня|ты меня разочаров\\p{L}*|разочаровал\\p{L}*|ты врешь|ты врёшь|ты соврал\\p{L}*|ты обманул\\p{L}*',
    ].join('|') +
    `)${W1}`,
);

export const RECONCILE_RE = rx(
  `${W0}(прости( меня)?|извини( меня)?|я (был|была) не прав\\p{L}*|я не прав\\p{L}*|давай мириться|помиримся|мирись|не обижайся|не злись|я погорячил\\p{L}*|давай поговорим|давай не будем (ссориться|ругаться)|забудем|я виноват\\p{L}*|больше не буду)${W1}`,
);

export const DRY_RE = /^(ок|окей|ясно|понятно|ладно|хорошо|понял|поняла|угу|ага|как хочешь|мне все равно|мне всё равно|ну ок|норм)[.!]?$/iu;
