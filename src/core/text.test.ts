import { describe, expect, it } from 'vitest';
import { isCheckin, isGreeting } from './text';

describe('isCheckin — вопрос о делах', () => {
  it.each([
    'Как дела?', 'как дела', 'Привет, как дела?', 'Привет! Как ты?', 'привет как ты', 'Ну как ты там?', 'Ты как?',
    'как у тебя дела', 'Как прошёл день?', 'как день прошел', 'Как спалось?', 'Что делаешь?', 'Чем занимаешься?',
    'Зай, как ты?', 'Доброе утро, как спалось?', 'Как самочувствие?', 'Ты в порядке?', 'Всё хорошо?', 'Как добралась?',
    'Что нового?', 'Як справи?', 'How are you?', 'hey, how are you doing', 'wyd', 'How was your day?',
    'Я дома. А ты как?', 'Купил хлеб. Как ты?',
  ])('да: %s', (t) => expect(isCheckin(t)).toBe(true));

  it.each([
    'А как ты меня отметишь?', 'Как ты меня бесишь', 'как ты это сделал?', 'Как дела с проектом обстоят у Пети?',
    'Я не знаю, как ты это терпишь', 'Расскажу, как дела пойдут', 'как ты думаешь, стоит?', 'Ты как хочешь',
    'Что делаешь с этим файлом?', 'Всё хорошо', 'ты в порядке, я вижу', 'Как ты мог!', 'Как вы там все умещаетесь?',
    'Чем занят Петя?', 'how are you going to fix it',
  ])('нет: %s', (t) => expect(isCheckin(t)).toBe(false));
});

describe('isGreeting — приветствие в начале', () => {
  it.each(['Привет!', 'Приветик)', 'Доброе утро ☀️', 'Ну привет', 'Хей, глянь', 'Всем привет', 'hi there', 'Добрый вечер!'])('да: %s', (t) =>
    expect(isGreeting(t)).toBe(true),
  );
  it.each(['Передай привет маме', 'Я сказал ему привет', 'Это был добрый день для всех нас', 'Хайп какой-то'])('нет: %s', (t) =>
    expect(isGreeting(t)).toBe(false),
  );
});
